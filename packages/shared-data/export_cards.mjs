// Run with the Cards workspace's installed tsx loader; no new dependencies.
import {writeFileSync} from 'node:fs';
import {BASE_CARDS} from '../../apps/cards/src/game/core/content.ts';
import rebirth from '../../apps/slay/public/content/cards.js';
import {HERO_CHARACTER_IDS} from '../shared-types/world.js';
const elements={金:'jin',木:'mu',水:'shui',火:'huo',土:'tu'};
const systems={生灵:'shengling',造物:'zaowu',空间:'kongjian',心灵:'xinling',锁御:'suoyu'};
const json=value=>JSON.parse(JSON.stringify(value));
const cards=Object.values(BASE_CARDS).map(c=>({id:'cards:'+c.id,mode:'cards',sourceId:c.id,name:c.name,
  characterId:HERO_CHARACTER_IDS[c.owner]||null,cost:c.cost,type:c.type,text:c.text,
  element:c.element||null,school:c.school||null,native:json(c)}));
for(const c of rebirth){
  const native=json(c), upgraded={...c,powers:c.powers?{...c.powers}:undefined,actions:c.actions?structuredClone(c.actions):undefined};
  if(c.upgrade)c.upgrade.call(upgraded);
  cards.push({id:'slay:'+c.name,mode:'slay',sourceId:c.name,name:c.name,characterId:null,cost:c.energy||0,
    type:c.type,text:c.description||'',element:elements[c.element]||null,
    school:elements[c.element]?'yuling':systems[c.element]||null,native,upgrade:c.upgrade?json(upgraded):null});
}
if(new Set(cards.map(c=>c.id)).size!==cards.length)throw new Error('Duplicate card source IDs');
const payload={schemaVersion:1,source:'mode-native-card-definitions',cards};
writeFileSync(new URL('./cards.json',import.meta.url),JSON.stringify(payload,null,2)+'\n');
writeFileSync(new URL('./cards-data.js',import.meta.url),'// Generated by export_cards.mjs.\nexport default '+JSON.stringify(payload)+';\n');
console.log(JSON.stringify({cards:cards.length,modes:Object.fromEntries(['cards','slay'].map(mode=>[mode,cards.filter(c=>c.mode===mode).length]))}));
