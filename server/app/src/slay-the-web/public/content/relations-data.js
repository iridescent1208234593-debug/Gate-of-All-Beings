// 按角色聚合：返回 {角色名: [关系, ...]}
export const relationsByCharacter = () => {
	const map = {}
	for (const r of relations) {
		for (const name of [r.a, r.b]) {
			if (name.includes('/')) continue // 聚合名（如 洛竹/虚淮/天虎）不展开
			;(map[name] = map[name] || []).push(r)
		}
	}
	for (const k of Object.keys(map)) {
		// 去重同一条关系（a/b 双向都挂）
		const seen = new Set()
		map[k] = map[k].filter((r) => {
			const key = [r.a, r.b, r.type, r.desc].join('|')
			if (seen.has(key)) return false
			seen.add(key)
			return true
		})
	}
	return map
}
