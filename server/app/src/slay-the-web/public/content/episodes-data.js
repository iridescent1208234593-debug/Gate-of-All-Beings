// —— 剧情回想抽取（供爬塔「剧情回想房」使用）——
// 按楼层推进对应篇目进度；只抽取有剧情概述的剧集（overview 为空的不作为回想内容）。
// 篇目覆盖度：相遇篇 2 集、下乡篇 10 集、蓝溪镇篇 4 集、众生之门篇 12 集——
// 各楼层均可抽到本层篇目的回想内容。
const FLOOR_CHAPTER_RANGES = [
	{minFloor: 0, maxFloor: 1, chapter: [1, 2], name: '相遇篇'},
	{minFloor: 2, maxFloor: 4, chapter: [3, 20], name: '下乡篇'},
	{minFloor: 5, maxFloor: 6, chapter: [21, 28], name: '蓝溪镇篇'},
	{minFloor: 7, maxFloor: 9, chapter: [29, 40], name: '众生之门篇'},
]
export const chapterForFloor = (floor = 0) =>
	FLOOR_CHAPTER_RANGES.find((r) => floor >= r.minFloor && floor <= r.maxFloor) ||
	FLOOR_CHAPTER_RANGES[FLOOR_CHAPTER_RANGES.length - 1]

/**
 * 按楼层抽取一集剧情回想（优先本层篇目 → 全局未看过 → 全局兜底）。
 * @param {number} floor 当前楼层（0-9，对齐 dungeon.js decideRoomType）
 * @param {Array<number>} usedEpisodeIds 本局已追忆过的集数（避免重复回想）
 * @returns {object|null} episodeList 中的单集（含 num/title/overview/cast）
 */
export function pickEpisodeForFloor(floor = 0, usedEpisodeIds = []) {
	const chapter = chapterForFloor(floor)
	const seen = new Set(usedEpisodeIds || [])
	const withOverview = (e) => e.overview && !seen.has(e.num)
	const inChapter = episodeList.filter(
		(e) => withOverview(e) && e.num >= chapter.chapter[0] && e.num <= chapter.chapter[1]
	)
	const pool = inChapter.length
		? inChapter
		: episodeList.filter(withOverview)
	const fallback = pool.length ? pool : episodeList.filter((e) => e.overview)
	if (!fallback.length) return null
	return fallback[Math.floor(Math.random() * fallback.length)]
}
