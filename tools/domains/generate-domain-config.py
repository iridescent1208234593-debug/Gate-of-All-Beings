"""Generate the browser/Node domain map and the standalone LAB host configuration."""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
config = json.loads((ROOT / "packages/site-domains/domains.json").read_text(encoding="utf-8"))
template = (ROOT / "packages/site-domains/template.js").read_text(encoding="utf-8")
output = template.replace("/* DOMAIN_CONFIG */", json.dumps(config, ensure_ascii=False, separators=(",", ":")))
callback_template = (ROOT / "tools/domains/direct-account-callback.js.in").read_text(encoding="utf-8")
callback = callback_template.replace("/* LAB_DIRECT_HOST */", json.dumps(config["labDirect"]["host"]))
targets = {
    "packages/site-domains/index.js": output,
    "apps/huiguan-lab/server/lab/site_domains.py": (
        '"""Generated by tools/domains/generate-domain-config.py."""\n\n'
        f"LAB_DIRECT_HOST = {config['labDirect']['host']!r}\n"
    ),
    "apps/huiguan-lab/web/static/direct-account-callback.js": callback,
}
for relative, contents in targets.items():
    target = ROOT / relative
    if "--check" in sys.argv:
        if not target.exists() or target.read_text(encoding="utf-8") != contents:
            raise SystemExit(f"{relative} needs regeneration")
    else:
        target.write_text(contents, encoding="utf-8", newline="\n")
