const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const sandbox = {};
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(path.join(__dirname,'../oc-revisions.js'),'utf8'),sandbox);
const revisions = sandbox.OCRevisions;
revisions.reset([{code:'A',_oc_version:1}]);
const openedFormVersion = revisions.version('A');
revisions.accept({code:'A',_oc_version:2});
assert.equal(openedFormVersion,1);
assert.equal(revisions.version('A'),2);
revisions.renamed('A',{code:'B',_oc_version:3});
assert.equal(revisions.version('A'),0);
assert.equal(revisions.version('B'),3);
revisions.reset([{code:'__proto__',_oc_version:4}]);
assert.equal(revisions.version('__proto__'),4);
assert.equal(revisions.version('B'),0);
console.log('OC revision transport: PASS');
